  await page.locator('#createForm').evaluate(e=>e.requestSubmit());
  const created=await (await createResponse).json();assert.equal(created.skill.id,selected.id);assert.deepEqual(created.skill,full);
  assert.equal(created.approval_mode,'manual');report.project=created.id;
  fs.writeFileSync(out+'/progress.json',JSON.stringify(report,null,2));
