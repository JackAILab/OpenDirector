  assert.equal(new Set(skills.map(s=>[s.reference_case.brand,s.reference_case.title].join('|').toLowerCase().replace(/[^\p{L}\p{N}]/gu,''))).size,100);
  report.skills=100;report.sources=[...new Set(skills.map(s=>s.reference_case.source_name))];
  report.categories=[...new Set(skills.map(s=>s.category))];
  await page.goto(origin+'/creative/discover?skills=reference#collection',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelectorAll('#skillGrid .method-card').length===100,null,{timeout:60000});
