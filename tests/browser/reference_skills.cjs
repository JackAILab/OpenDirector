  await page.locator('#skillDetail video').evaluate(v=>v.load());
  await page.waitForFunction(()=>document.querySelector('#skillDetail video').readyState>=1,null,{timeout:45000});
  await page.locator('.reference-evidence summary').click();
  const index=full.source_evidence.findIndex(b=>b.start>0);assert(index>=0);
  await page.locator('.reference-evidence button').nth(index).click();
  await page.waitForFunction(t=>{const v=document.querySelector('#skillDetail video');return !v.seeking&&Math.abs(v.currentTime-t)<.7},full.source_evidence[index].start,{timeout:45000});
  report.source_preview=true;report.evidence_seek=true;
  await page.locator('#skillDetail').evaluate(e=>e.scrollTop=0);await page.screenshot({path:out+'/desktop-detail.png'});
  step('mobile');await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('#skillDetail').evaluate(e=>e.scrollWidth<=e.clientWidth+1),true);
  await page.screenshot({path:out+'/mobile-detail.png'});
  await page.locator('#skillDetail .dialog-head button').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#skillSearch').fill('');
  await page.locator('.method-category').selectOption('商品动作证明');
  assert.equal(await page.locator('#skillGrid .method-card').count(),skills.filter(s=>s.category==='商品动作证明').length);
  report.mobile_no_overflow=true;report.search_and_filter=true;
  step('private-copy');await page.setViewportSize({width:1440,height:1000});
  await page.locator('.method-category').selectOption('全部');await page.locator('#skillSearch').fill(selected.reference_case.title);
  await card.getByRole('button',{name:'查看方法',exact:true}).click();await page.waitForSelector('#skillDetail .reference-timeline');
  await page.getByRole('button',{name:'另存为我的 Skill',exact:true}).click();
