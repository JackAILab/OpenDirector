  await page.locator('#entryApproval').selectOption('manual');
  await page.locator('#quickForm').evaluate(e=>e.requestSubmit());
  await page.waitForURL('**/creative?new=1');await page.waitForSelector('#newDialog[open]',{timeout:45000});
  await page.waitForFunction(id=>{const e=document.querySelector('#initialSkill');return !e.disabled&&e.value===id},selected.id,{timeout:45000});
