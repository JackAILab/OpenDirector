  step('detail-and-preview');
  await page.locator('#skillSearch').fill(selected.reference_case.title);
  const card=page.locator('[data-skill-id="'+selected.id+'"]');assert(await card.isVisible());
  await card.getByRole('button',{name:'查看方法',exact:true}).click();
  await page.waitForSelector('#skillDetail .reference-timeline');
  assert((await page.locator('#skillDetail').textContent()).includes('导演应追问什么'));
  const full=await (await context.request.get(origin+'/creative/api/skills/'+selected.id+'?version='+selected.version)).json();
