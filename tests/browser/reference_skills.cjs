  await context.addInitScript(key=>sessionStorage.setItem('h3_api_key',key),account.api_key);
  const page=await context.newPage(),errors=[],forbidden=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST'&&/\/(execute|generate|images\/create)(\?|$)/.test(r.url()))forbidden.push(new URL(r.url()).pathname)});
  step('catalog');
