  report.private_copy=saved.id;await page.locator('#skillDetail .dialog-head button').click();
  step('choose-to-new-project');
  await page.locator('[data-tab="reference"]').click();
  await card.getByRole('button',{name:'选择 ↗',exact:true}).click();
  assert.equal(await page.locator('#entrySkill').inputValue(),selected.id);
  const prompt='【Skill上线验收】为无品牌木质调概念香水创作15秒广告，16:9，有音乐、同步音效和简短中文旁白，一次生成整片。商品为无标签琥珀色圆柱玻璃瓶、黑色圆柱瓶盖。已知只有外观和下班后留给自己的片刻这一情绪目标；不写成分、具体香材、持香时长、功效、价格。受众是忙碌都市成年人；画面温暖克制、真实住宅夜晚。借鉴所选Skill的机制，换成新商品动作，不能复制原广告。允许合理视觉假设，不需要继续追问，直接规划。这里只做方案，手动确认后才生成视频。';
